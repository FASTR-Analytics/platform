// Builds styles/report-forge.css, the one stylesheet a host imports.
//
//   node styles/build.mjs           write it
//   node styles/build.mjs --check   fail if the committed file is stale
//
// The file is kit.css (the hand-written components) followed by the utility
// classes the package's source uses: every `rf:` class found in a .ts/.tsx
// file under ui/, compiled by Tailwind against the theme in utilities.css.
// The result is committed, so a host needs no CSS tooling of its own. Run
// this after adding or changing an `rf:` class.
//
// Tailwind is a tool of this script only; it is resolved from the
// playground's node_modules (npm install there once).

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const require = createRequire(path.join(root, "playground", "package.json"));

const tw = (await import(require.resolve("tailwindcss"))).default;
const twDir = path.dirname(require.resolve("tailwindcss/package.json"));

function sourceFiles(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name === "dist") continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) sourceFiles(full, out);
    else if (/\.tsx?$/.test(entry.name)) out.push(full);
  }
  return out;
}

// A class is anything from `rf:` up to the next character that cannot be
// part of one. Arbitrary values may hold quotes, so brackets are balanced.
function classesIn(text) {
  const found = new Set();
  const start = /(?<![\w-])rf:/g;
  let m;
  while ((m = start.exec(text)) !== null) {
    let i = m.index + 3;
    let depth = 0;
    for (; i < text.length; i++) {
      const c = text[i];
      if (c === "[" || c === "(") depth++;
      else if (c === "]" || c === ")") {
        if (depth === 0) break;
        depth--;
      } else if (depth === 0 && /[\s"'`<>{},;]/.test(c)) break;
    }
    const cls = text.slice(m.index, i);
    if (cls.length > 3) found.add(cls);
  }
  return found;
}

const candidates = new Set();
for (const dir of ["ui", "playground/src"]) {
  const abs = path.join(root, dir);
  if (!fs.existsSync(abs)) continue;
  for (const file of sourceFiles(abs)) {
    for (const cls of classesIn(fs.readFileSync(file, "utf8"))) {
      candidates.add(cls);
    }
  }
}

const compiler = await tw.compile(
  fs.readFileSync(path.join(here, "utilities.css"), "utf8"),
  {
    base: here,
    loadStylesheet: (id, base) => {
      const file = id.startsWith("tailwindcss/")
        ? path.join(twDir, id.slice("tailwindcss/".length))
        : path.resolve(base, id);
      return Promise.resolve({
        path: file,
        base: path.dirname(file),
        content: fs.readFileSync(file, "utf8"),
      });
    },
  },
);
const sorted = [...candidates].sort();
// The tokens are declared on the page root, and again on .rf-root so that a
// host may set a --forge-* variable on any ancestor of the editor, not only
// on :root (a custom property is resolved where it is declared).
const utilities = compiler.build(sorted).replace(
  ":root, :host {",
  ":root, :host, .rf-root {",
);

// A class the compiler does not know produces no rule, and the element
// silently loses that style. Name every one.
const unknown = sorted.filter((cls) => {
  const escaped = cls.replace(/[^a-zA-Z0-9_-]/g, (c) => `\\${c}`);
  return !utilities.includes(`.${escaped}`);
});
if (unknown.length > 0) {
  console.error(
    `These classes compile to nothing (a typo, or a utility the theme does not define):\n  ${
      unknown.join("\n  ")
    }`,
  );
  process.exit(1);
}

const css = [
  "/* GENERATED by styles/build.mjs from kit.css and utilities.css. Do not",
  "   edit: change the source and run `npm run styles` in playground/. */",
  "",
  fs.readFileSync(path.join(here, "kit.css"), "utf8").trimEnd(),
  "",
  "/* ── Utilities ─────────────────────────────────────────────────────────── */",
  "",
  utilities.trimEnd(),
  "",
].join("\n");

const target = path.join(here, "report-forge.css");
if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== css) {
    console.error(
      "styles/report-forge.css is stale: run `npm run styles` in playground/.",
    );
    process.exit(1);
  }
  console.log(`OK: report-forge.css is current (${sorted.length} utilities).`);
} else {
  fs.writeFileSync(target, css);
  console.log(
    `Wrote report-forge.css: ${sorted.length} utilities, ${css.length} bytes.`,
  );
}
